import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, readFile, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { Store } from '../lib/store.mjs';
import { Worker } from '../lib/jobs.mjs';
import { encoder } from '../lib/render.mjs';
import { scriptFor } from '../lib/domain.mjs';
import { temporaryFolder } from './helpers.mjs';
test('full worker saves a ready video and reuses narration on render retry', { skip: !encoder(), timeout: 120000 }, async t => {
  const dir = await temporaryFolder(t, 'worker-');
  const originalFetch = globalThis.fetch, originalKey = process.env.ELEVENLABS_API_KEY;
  t.after(async () => { globalThis.fetch = originalFetch; if (originalKey === undefined) delete process.env.ELEVENLABS_API_KEY; else process.env.ELEVENLABS_API_KEY = originalKey; });
  await promisify(execFile)(encoder(), ['-y', '-f', 'lavfi', '-i', 'sine=frequency=330:duration=2', '-c:a', 'libmp3lame', join(dir, 'fixture.mp3')], { windowsHide: true });
  const audio = (await readFile(join(dir, 'fixture.mp3'))).toString('base64');
  const scenes = [{ id: 'one', title: 'Working memory', narration: 'RAM is working memory.', labels: ['Working data', 'Current task'], kind: 'flow' }, { id: 'two', title: 'Saved files', narration: 'Storage holds saved files.', labels: ['Saved file', 'Open later'], kind: 'comparison' }];
  const characters = Array.from(scriptFor(scenes)); let calls = 0;
  process.env.ELEVENLABS_API_KEY = 'test-only-placeholder';
  globalThis.fetch = async () => { calls++; return new Response(JSON.stringify({ audio_base64: audio, alignment: { characters, character_start_times_seconds: characters.map((_, i) => i * 1.9 / characters.length), character_end_times_seconds: characters.map((_, i) => (i + 1) * 1.9 / characters.length) } }), { status: 200 }); };
  const store = new Store(join(dir, 'data')); await store.init(); const worker = new Worker(store);
  await store.update(db => { db.projects.push({ id: 'project', ownerId: 'one', scenes, revision: 1 }); db.jobs.push({ id: 'job-one', ownerId: 'one', projectId: 'project', revision: 1, kind: 'generate', state: 'queued', voiceId: 'test-voice' }); });
  await worker.tick();
  assert.equal(store.data.jobs[0].state, 'succeeded', store.data.jobs[0].error); assert.equal(store.data.projects[0].status, 'ready'); assert.equal(calls, 1);
  const firstDirectory = store.data.projects[0].output.directory;
  await store.update(db => { db.jobs.push({ id: 'job-two', ownerId: 'one', projectId: 'project', revision: 1, kind: 'generate', state: 'queued', voiceId: 'test-voice' }); });
  await worker.tick(); assert.equal(store.data.jobs[1].state, 'succeeded', store.data.jobs[1].error); assert.equal(calls, 1); assert.notEqual(store.data.projects[0].output.directory, firstDirectory); assert.equal(store.data.projects[0].previousOutputs[0].directory, firstDirectory);
});
